#!/usr/bin/env bash
# Install scry from this checkout.
#
# One tracked source tree, one generated launcher. Nothing is copied, so there is no
# second copy to drift out of date. Idempotent: safe to re-run after a pull.
#
#   ./install.sh              install for the current user
#   ./install.sh --check      report what is installed, change nothing
#
# Requires python3 >= 3.11 (tomllib) with sqlite3 FTS5. No third-party deps.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN="${BIN_DIR:-$HOME/.local/bin}"
CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1

launcher() { # $1 = command name, $2 = python module path
    cat <<EOF
#!/usr/bin/env python3
"""$1 launcher. Generated by install.sh -- edit the repo, not this file."""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path("$REPO")


def main() -> int:
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from $2 import main as entry

    return entry(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
EOF
}

report() { printf '  %-34s %s\n' "$1" "$2"; }

# --- preflight -------------------------------------------------------------
python3 - <<'PY' || { echo "install.sh: python3 prerequisites not met" >&2; exit 1; }
import sqlite3, sys, tomllib
assert sys.version_info >= (3, 11), f"need python >= 3.11, have {sys.version_info[:2]}"
sqlite3.connect(":memory:").execute("create virtual table t using fts5(x)")
PY

if (( CHECK )); then
    echo "scry install status"
    report "repo" "$REPO"
    if [[ -e "$BIN/scry" ]]; then
        report "$BIN/scry" "$(grep -m1 '^REPO' "$BIN/scry" || echo '(regular file)')"
    else
        report "$BIN/scry" "ABSENT"
    fi
    exit 0
fi

mkdir -p "$BIN"

launcher scry "scry.cli" > "$BIN/scry"
chmod 755 "$BIN/scry"
report "installed" "$BIN/scry"

echo
echo "First run builds the index (minutes on a large machine; incremental afterwards):"
echo "  scry"
